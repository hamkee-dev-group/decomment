static int check_case(const strip_case_t *test)
{
    const dc_lang_t *language = dc_lang_find(test->language);
    dc_buf_t output;
    dc_buf_init(&output);
    dc_result_t result = language->strip(test->input, strlen(test->input), &output, language->flags);
    size_t expected_len = strlen(test->expected);
    int failed = result != DC_OK || output.len != expected_len ||
                 (expected_len > 0 && memcmp(output.data, test->expected, expected_len) != 0);
    if (failed) {
        fprintf(stderr, "%s (%s): expected [%s], got [%.*s], result %d\n",
                test->name, test->language, test->expected, (int)output.len,
                output.data ? output.data : "", (int)result);
    }
    dc_buf_free(&output);
    return failed;
}

int main(void)
{
    size_t failures = 0;
    dc_lang_init();
    for (size_t i = 0; i < sizeof(cases) / sizeof(cases[0]); i++)
        failures += (size_t)check_case(&cases[i]);
    size_t total = sizeof(cases) / sizeof(cases[0]);
    const dc_lang_t *const *languages = dc_lang_all();
    for (size_t i = 0; languages[i]; i++) {
        strip_case_t empty = {"empty input", languages[i]->name, "", ""};
        failures += (size_t)check_case(&empty);
        total++;
    }
    printf("%zu cases, %zu failures\n", total, failures);
    return failures ? 1 : 0;
}
